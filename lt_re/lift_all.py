#!/usr/bin/env python3
"""Static translation of ALL code of lithtech.exe (instruction list from Ghidra) into GAS Intel asm.
Outputs: lifted_all.s, lttext.bin (original .text bytes kept at their VA for table reads), ltpatch table inside the .s.
"""
import re,json,collections,pefile,sys
from capstone import Cs,CS_ARCH_X86,CS_MODE_32
from capstone.x86 import X86_OP_IMM
import os; exe=os.environ.get('LT_EXE','/mnt/user-data/uploads/lithtechreal.exe')
pe=pefile.PE(exe); base=pe.OPTIONAL_HEADER.ImageBase; raw=open(exe,'rb').read()
text=next(s for s in pe.sections if s.Name.startswith(b'.text')); tva=base+text.VirtualAddress; tsz=text.Misc_VirtualSize; tend=tva+tsz
tb=raw[text.PointerToRawData:text.PointerToRawData+text.SizeOfRawData]
units=[tuple(int(x,16) if k==0 else int(x) for k,x in enumerate(l.split())) for l in open('/tmp/code_units.txt' if __import__('os').path.exists('/tmp/code_units.txt') else 'data/code_units.txt')]
units.sort()
S={u[0]:u[1] for u in units}
# runs of contiguous instructions
runs=[];cur=None
for a,l in units:
    if cur and cur[1]==a: cur[1]=a+l
    else:
        if cur: runs.append(tuple(cur))
        cur=[a,a+l]
runs.append(tuple(cur))
md=Cs(CS_ARCH_X86,CS_MODE_32); md.detail=True
STR={'movsb','movsw','movsd','stosb','stosw','stosd','lodsb','lodsw','lodsd','scasb','scasw','scasd','cmpsb','cmpsw','cmpsd'}
need=set(); lines=[]; bad=[]; warn=collections.Counter()
def lab(a): need.add(a); return '.Llt_%08x'%a
def tr(i):
    mn=i.mnemonic; op=i.op_str; core=mn.split(' ')[-1]; pre=' '.join(mn.split(' ')[:-1])
    if core in STR: return (pre+' ' if pre else '')+core
    isbr=core in('jmp','call') or core.startswith('j') or core.startswith('loop')
    if isbr and i.operands and i.operands[0].type==X86_OP_IMM:
        t=i.operands[0].imm&0xffffffff
        if t in S: return mn+' '+lab(t)
        warn['branch to non-instruction']+=1; bad.append((hex(i.address),mn,op)); return mn+' 0x%08x'%t
    def rep(m):
        v=int(m.group(0),16)
        if v in S: return 'offset '+lab(v)
        return m.group(0)
    if '[' in op:
        k=op.index('['); line=(mn+' '+re.sub(r'\b0x[0-9a-f]{6,8}\b',rep,op[:k])+op[k:]).strip()
    else: line=(mn+' '+re.sub(r'\b0x[0-9a-f]{6,8}\b',rep,op)).strip()
    return line.replace('xword ptr','tbyte ptr')
body=[]
for rs,re_ in runs:
    code=raw[text.PointerToRawData+rs-tva:text.PointerToRawData+re_-tva]
    pos=rs
    for i in md.disasm(code,rs):
        if i.size!=S.get(i.address): warn['length mismatch']+=1; bad.append((hex(i.address),'len',i.size,S.get(i.address)))
        body.append((i.address,tr(i))); pos=i.address+i.size
    if pos!=re_:  # capstone stopped early -> emit rest as bytes
        warn['capstone stopped early']+=1; bad.append((hex(pos),'stop'))
        body.append((pos,'.byte '+','.join(str(b) for b in raw[text.PointerToRawData+pos-tva:text.PointerToRawData+re_-tva])))
    body.append((None,None))  # run break
# data references to code: dwords in data image and in non-code bytes of .text
import json as _j; _L=_j.load(open('layout.json')); img=open('ltdata.bin','rb').read(); lo=_L['data']
patch=[]  # (address of dword, target VA)
for k in range(0,len(img)-3,4):
    v=int.from_bytes(img[k:k+4],'little')
    if v in S: patch.append((lo+k,v))
covered=bytearray(tsz)
for a,l in units:
    covered[a-tva:a-tva+l]=b'\x01'*l
for k in range(0,len(tb)-3):
    if k%4: continue
    if any(covered[k:k+4]): continue
    v=int.from_bytes(tb[k:k+4],'little')
    if v in S: patch.append((tva+k,v))
for a,v in patch: need.add(v)
need.add(base+pe.OPTIONAL_HEADER.AddressOfEntryPoint)
glob={v for _,v in patch}
out=['/* generated by lift_all.py: static translation of lithtech.exe .text */','.intel_syntax noprefix','.text']
for a,l in body:
    if a is None: continue
    s=''
    s+='.Llt_%08x:\n'%a
    if a in glob: s+='.globl _lt_L_%08x\n_lt_L_%08x:\n'%(a,a)
    out.append(s+'  '+l)
out+= ['.data','.globl _lt_patch_tab','_lt_patch_tab:']
out+=['  .long 0x%08x, .Llt_%08x'%(a,v) for a,v in sorted(set(patch))]
out+=['  .long 0, 0','.text','.globl _lt_entry','_lt_entry:','  jmp .Llt_%08x'%(base+pe.OPTIONAL_HEADER.AddressOfEntryPoint)]
need.add(base+pe.OPTIONAL_HEADER.AddressOfEntryPoint)
# entry label must exist: re-add if missing label emission
open('lifted_all.s','w').write('\n'.join(out)+'\n')
json.dump(bad[:200],open('lift_all_bad.json','w'))
print('instructions',len(S),'runs',len(runs),'| data->code patches',len(patch),'| labels',len(need),'|',dict(warn))

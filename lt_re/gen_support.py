#!/usr/bin/env python3
"""Generate c/lt_support.c: global data (initialised from lithtech.exe), import adaptors, pseudo-ops."""
import re,subprocess,pefile,glob
exe='/mnt/user-data/uploads/lithtech.exe'; mss='/mnt/user-data/uploads/mss32.dll'
pe=pefile.PE(exe); base=pe.OPTIONAL_HEADER.ImageBase; data=open(exe,'rb').read()
def rd(va,n):
    for s in pe.sections:
        a=base+s.VirtualAddress
        if a<=va<a+s.Misc_VirtualSize:
            o=va-a
            if o+n<=s.SizeOfRawData: return data[s.PointerToRawData+o:s.PointerToRawData+o+n]
            return b'\0'*n
    return b'\0'*n
def cstr(va):
    out=b''
    while len(out)<512:
        b=rd(va+len(out),1)
        if b==b'\0': break
        out+=b
    return out
und=[l.strip() for l in open('/tmp/undef.txt') if l.strip()]

glob_h=open('c/lt_globals.h').read()
decl={}
for m in re.finditer(r'extern (undefined4|char|void|float|double|uint8_t|uint16_t)\s*(\*?)\s*(\w+)(\[\d*\]|\(void\))?;',glob_h): decl[m.group(3)]=(m.group(1)+(' *' if m.group(2) else ''),m.group(4))
o=['/* generated by gen_support.py */','#include <windows.h>','#undef DWORD','#undef BOOL','#undef WORD','#undef HANDLE','#undef ULONG',
'#define main_unused 1','']
# windows.h conflicts with my typedefs -> keep this file free of ghidra_types.h; define data with plain C types
o=['/* generated by gen_support.py: data + import adaptors + pseudo-ops. No ghidra_types.h on purpose. */','#include <windows.h>','#include <math.h>','#include <stdint.h>','#undef NAN','#undef InterlockedIncrement','#undef InterlockedDecrement','#undef InterlockedExchange','']
asm=[];ptrs=[];inits=[]
mssexp={e.name.decode() for e in pefile.PE(mss).DIRECTORY_ENTRY_EXPORT.symbols if e.name}
# arity table from mingw libs
ar={}
for lib in ['kernel32','user32','gdi32','winmm','ole32','ws2_32','advapi32']:
    r=subprocess.run(['nm','-g','/usr/i686-w64-mingw32/lib/lib%s.a'%lib],capture_output=True,text=True).stdout
    for m in re.finditer(r'^[0-9a-f]* T _(\w+)@(\d+)$',r,re.M): ar.setdefault(m.group(1),int(m.group(2)))
ords={2:'bind',3:'closesocket',6:'getsockname',8:'htonl',9:'htons',10:'ioctlsocket',12:'inet_ntoa',14:'ntohl',15:'ntohs',17:'recvfrom',20:'sendto',23:'socket',52:'gethostbyname',111:'WSAGetLastError',116:'WSACleanup'}
def adaptor(sym,N,target,indirect=False):
    s='.globl _%s\n_%s:\n pushl %%ebp\n movl %%esp,%%ebp\n'%(sym,sym)
    for i in range(N//4-1,-1,-1): s+=' pushl %d(%%ebp)\n'%(8+4*i)
    s+=(' call *_p_%s\n'%sym if indirect else ' call _%s\n'%target)
    s+=' popl %ebp\n ret\n'
    return s
AT_VA=True
done=set(); other=[]
for n in und:
    m=re.match(r'^(DAT|PTR|s|u|_DAT|PTR_s|PTR_LAB|PTR_FUN|PTR_DAT)_.*?([0-9a-f]{8})$',n)
    if n in done: continue
    done.add(n)
    if m and n in decl and AT_VA and 0x4cb000<=int(m.group(2),16)<0x4ef000: continue
    if m and n in decl:
        va=int(m.group(2),16); kind,sfx=decl[n]
        if sfx and sfx.startswith('[') and kind=='float':
            import struct; N=int(sfx[1:-1]); o.append('float %s[%d]={%s};'%(n,N,','.join(repr(struct.unpack('<f',rd(va+4*q,4))[0]).replace('nan','__builtin_nanf("")').replace('inf','__builtin_inff()') for q in range(N))))
        elif kind in('float','double'):
            import struct; sz=4 if kind=='float' else 8
            o.append('%s %s=%s;'%(kind,n,repr(struct.unpack('<f' if sz==4 else '<d',rd(va,sz))[0]).replace('nan','__builtin_nan("")').replace('inf','__builtin_inf()')))
        elif kind in('uint8_t','uint16_t'): o.append('%s %s=%d;'%(kind,n,int.from_bytes(rd(va,1 if kind=='uint8_t' else 2),'little')))
        elif sfx=='[]': o.append('char %s[]={%s};'%(n,','.join(str(b) for b in cstr(va)+b'\0')))
        elif kind=='undefined4 *': o.append('uint32_t *%s=(uint32_t*)0x%08xu;'%(n,int.from_bytes(rd(va,4),'little')))
        elif kind in('float','double'):
            import struct; sz=4 if kind=='float' else 8
            o.append('%s %s=%s;'%(kind,n,repr(struct.unpack('<f' if sz==4 else '<d',rd(va,sz))[0]).replace('nan','__builtin_nan("")').replace('inf','__builtin_inf()')))
        elif kind in('uint8_t','uint16_t'): o.append('%s %s=%d;'%(kind,n,int.from_bytes(rd(va,1 if kind=='uint8_t' else 2),'little')))
        elif kind=='void': o.append('void %s(void){__builtin_trap();}'%n)
        else: o.append('uint32_t %s=0x%08xu;'%(n,int.from_bytes(rd(va,4),'little')))
    elif n.startswith(('LAB_','LOOP_','switchD_','caseD_')): o.append('void %s(void){__builtin_trap();}'%n)
    elif n.startswith('thunk_FUN_'): asm.append('.globl _%s\n_%s: jmp _%s\n'%(n,n,n[6:]))
    elif n.startswith('_AIL_') or n.startswith('AIL_'):
        mm=re.match(r'^_?(AIL_\w+?)_(\d+)$',n); base_,N=mm.group(1),int(mm.group(2))
        exp=next((c for c in ['_%s@%d'%(base_,N),'%s'%base_,'_%s'%base_] if c in mssexp),None)
        if exp is None: o.append('void %s(void){__builtin_trap();} /* no mss32 export */'%n); continue
        asm.append(adaptor(n,N,None,True)); ptrs.append(n); inits.append((n,exp))
    elif n.startswith('Ordinal_'):
        k=int(n.split('_')[1]); t=ords.get(k)
        if t: asm.append(adaptor(n,ar.get(t,0),t+'@%d'%ar.get(t,0)))
        else: o.append('void %s(void){__builtin_trap();}'%n)
    elif n in('InterlockedIncrement','InterlockedDecrement','InterlockedExchange'):
        o.append({'InterlockedIncrement':'long InterlockedIncrement(volatile long*p){return __sync_add_and_fetch(p,1);}','InterlockedDecrement':'long InterlockedDecrement(volatile long*p){return __sync_sub_and_fetch(p,1);}','InterlockedExchange':'long InterlockedExchange(volatile long*p,long v){return __sync_lock_test_and_set(p,v);}'}[n])
    elif n in ar: asm.append(adaptor(n,ar[n],'%s@%d'%(n,ar[n])))
    elif re.match(r'^CONCAT\d\d$',n):
        y=int(n[-1]); o.append('uint32_t %s(uint32_t a,uint32_t b){return (a<<%d)|(b&%su);}'%(n,min(8*y,31),'0xffffffff' if y>=4 else hex((1<<(8*y))-1)))
    elif n=='ExceptionList': o.append('uint32_t ExceptionList;')
    elif n in('ABS','SQRT','ROUND','fsin','fcos','fpatan','fscale','NAN','LOCK','UNLOCK','builtin_memcpy'):
        o.append({'ABS':'double ABS(double x){return fabs(x);}','SQRT':'double SQRT(double x){return sqrt(x);}','ROUND':'double ROUND(double x){return round(x);}',
        'fsin':'double fsin(double x){return sin(x);}','fcos':'double fcos(double x){return cos(x);}','fpatan':'double fpatan(double a,double b){return atan2(b,a);}',
        'fscale':'double fscale(double a,double b){return ldexp(a,(int)b);}','NAN':'int NAN(double x){return x!=x;}','LOCK':'void LOCK(void){}','UNLOCK':'void UNLOCK(void){}',
        'builtin_memcpy':'void *builtin_memcpy(void*d,const void*s,size_t n){return __builtin_memcpy(d,s,n);}'}[n])
    elif n.startswith('@'): asm.append('.globl %s\n%s: ud2\n'%(n,n))
    else: o.append('void %s(void){__builtin_trap();} /* unresolved reference */'%n); other.append(n)
for p in ptrs: o.append('void *p_%s_;'%p)
o.append('__asm__(".data\\n'+''.join('.globl _p_%s\\n_p_%s: .long 0\\n'%(p,p) for p in ptrs)+'.text\\n");')
for a in asm: o.append('__asm__(\n'+'\n'.join('  "%s\\n"'%ln for ln in ('.text\n'+a).strip('\n').split('\n'))+');')
o.append('void lt_resolve_init(void){ HMODULE h=LoadLibraryA("mss32.dll"); if(!h) return;')
for n,e in inits: o.append('  { extern void *p_%s __asm__("_p_%s"); p_%s=(void*)GetProcAddress(h,"%s"); }'%(n,n,n,e))
o.append('}')
o.append('extern void lt_iat_init(void); extern void lt_fixup_init(void); extern void entry(void);\nvoid lt_start(void){ lt_iat_init(); lt_resolve_init(); lt_fixup_init(); entry(); ExitProcess(0); }')
# fix: p_ externs must be declared before use
dec=''.join('extern void *p_%s __asm__("_p_%s");\n'%(p,p) for p in ptrs)
txt='\n'.join(o).replace('/* generated by gen_support.py: data','%s/* generated by gen_support.py: data'%dec,1) if False else '\n'.join(o)
txt=txt.replace('void *p_%s_;'%ptrs[0],'') if False else txt
txt=re.sub(r'void \*p_\w+_;\n','',txt)
open('c/lt_support.c','w').write(txt.replace('#include <stdint.h>\n','#include <stdint.h>\n'+dec,1))
open('/tmp/other_undef.txt','w').write('\n'.join(other))
print('adaptors',len(asm),'unhandled',len(other),other[:20])

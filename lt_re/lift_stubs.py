#!/usr/bin/env python3
"""Replace every STUBbed C function by its ORIGINAL x86 code (disassembled from lithtech.exe) as top-level asm."""
import re,glob,json,subprocess,collections,pefile
from capstone import Cs,CS_ARCH_X86,CS_MODE_32
from capstone.x86 import X86_OP_IMM
exe='/mnt/user-data/uploads/lithtech.exe'
pe=pefile.PE(exe); base=pe.OPTIONAL_HEADER.ImageBase; raw=open(exe,'rb').read()
text=next(s for s in pe.sections if s.Name.startswith(b'.text')); tva=base+text.VirtualAddress; tend=tva+text.Misc_VirtualSize
def code(va,n): o=text.PointerToRawData+va-tva; return raw[o:o+n]
# VA -> C name, size
fm={};sz={}
import os
SRC='/tmp/old/lt_re/c' if os.path.isdir('/tmp/old/lt_re/c') else 'c'
for f in glob.glob(SRC+'/*.c'):
    if f.endswith(('lt_support.c','lt_fixups.c','lt_lifted.c','lt_iat.c')): continue
    t=open(f).read()
    for m in re.finditer(r'^/\* ([0-9a-f]{8}) size=(\d+)[^\n]*\*/\n(.*?)^\{',t,re.M|re.S):
        head=re.sub(r'/\*.*?\*/','',m.group(3),flags=re.S)
        nm=re.search(r'(\w+)\(',head)
        va=int(m.group(1),16); sz[va]=int(m.group(2))
        if nm: fm[va]=nm.group(1)
json.dump({hex(k):[v,sz[k]] for k,v in fm.items() if k in sz},open('funcmap.json','w'))
inv={v:k for k,v in fm.items()}
# C name -> asm symbol from the objects
symmap={}
nmout=subprocess.run('i686-w64-mingw32-nm obj/*.o',shell=True,capture_output=True,text=True).stdout
for m in re.finditer(r'^[0-9a-f]+ T (\S+)$',nmout,re.M):
    s=m.group(1); name=s[1:].rsplit('@',1)[0] if s.startswith('@') else s[1:]
    symmap[name]=s

# symbols for functions whose C body no longer exists: compile their prototypes to learn the exact decoration
protos={}
for l in open('c/lt_protos.h'):
    m=re.search(r'(\w+)\(',l)
    if m and l.strip().endswith(';'): protos[m.group(1)]=l.strip()[:-1]
stubnames=[n for n in json.load(open('stubbed_functions.json')) if n in protos]
open('/tmp/symgen.c','w').write('#include "ghidra_types.h"\n'+'\n'.join(protos[n]+' { __builtin_trap(); }' for n in stubnames)+'\n')
subprocess.run(['i686-w64-mingw32-gcc','-c','-w','-fpermissive','-I','c','-x','c','/tmp/symgen.c','-o','/tmp/symgen.o'],check=True)
for m in re.finditer(r'^[0-9a-f]+ T (\S+)$',subprocess.run(['i686-w64-mingw32-nm','/tmp/symgen.o'],capture_output=True,text=True).stdout,re.M):
    s_=m.group(1); symmap[s_[1:].rsplit('@',1)[0] if s_.startswith('@') else s_[1:]]=s_
# IAT: slot VA -> True ; thunk VA -> slot
iat={}
for d in pe.DIRECTORY_ENTRY_IMPORT:
    for imp in d.imports: iat[imp.address]=1
md=Cs(CS_ARCH_X86,CS_MODE_32); md.detail=True
def thunk_slot(va):
    if not tva<=va<tend: return None
    for i in md.disasm(code(va,6),va):
        if i.mnemonic=='jmp' and i.op_str.startswith('dword ptr [0x'):
            s=int(i.op_str[i.op_str.index('0x'):-1],16)
            if s in iat: return s
        break
    return None
STR={'movsb','movsw','movsd','stosb','stosw','stosd','lodsb','lodsw','lodsd','scasb','scasw','scasd','cmpsb','cmpsw','cmpsd'}
stubs=json.load(open('stubbed_functions.json'))
funcs_info=[]; allinstr=set(); warn=[]
def sym(name): return '"%s"'%symmap[name]
out=['/* generated by lift_stubs.py: original x86 code of functions whose decompilation did not compile */','__asm__(".intel_syntax noprefix\\n");']
labels_global=set()
lifted=[]
for name in stubs:
    if name not in inv: warn.append(('no VA',name)); continue
    va=inv[name]; n=sz[va]; end=va+n
    ins=list(md.disasm(code(va,n),va))
    if not ins or ins[-1].address+ins[-1].size!=end: warn.append(('extent mismatch',name,hex(va),n)); continue
    lifted.append((name,va,end,ins))
    for i in ins: allinstr.add(i.address)
ranges=[(va,end) for _,va,end,_ in lifted]
def inr(a): return any(s<=a<e for s,e in ranges)
need=set()  # local labels needed
bodies=[]
for name,va,end,ins in lifted:
    b=[]
    def tgt(a,kind):
        if va<=a<end: need.add(a); return '.Llt_%08x'%a
        if a in fm and fm[a] in symmap: return sym(fm[a])
        s=thunk_slot(a)
        if s is not None: return 'dword ptr [0x%08x]'%s
        if inr(a): need.add(a); return '.Llt_%08x'%a
        warn.append(('unresolved %s target'%kind,name,hex(a))); return '0x%08x'%a
    for i in ins:
        mn=i.mnemonic; op=i.op_str
        parts=mn.split(' '); core=parts[-1]; pre=' '.join(parts[:-1])
        if core in STR: line=(pre+' ' if pre else '')+core
        elif core in('jmp','call') and i.operands and i.operands[0].type==X86_OP_IMM: line=mn+' '+tgt(i.operands[0].imm,core)
        elif (core.startswith('j') or core.startswith('loop')) and i.operands and i.operands[0].type==X86_OP_IMM: line=mn+' '+tgt(i.operands[0].imm,core)
        else:
            def rep(m):
                v=int(m.group(0),16)
                if v in fm and fm[v] in symmap and tva<=v<tend: return 'offset '+sym(fm[v])
                if inr(v) and tva<=v<tend and v not in(): need.add(v); return 'offset .Llt_%08x'%v
                return m.group(0)
            if '[' in op:
                a,bb=op.split('[',1) if op.count('[')==1 else (op,'')
                # only substitute outside brackets
                pre_=re.sub(r'0x[0-9a-f]{6,8}',rep,op[:op.index('[')]); line=(mn+' '+pre_+op[op.index('['):]).strip()
            else: line=(mn+' '+re.sub(r'\b0x[0-9a-f]{6,8}\b',rep,op)).strip()
        line=line.replace('xword ptr','tbyte ptr'); b.append((i.address,line))
    bodies.append((name,va,b))
for name,va,b in bodies:
    out.append('__asm__(".text\\n.p2align 4\\n.globl %s\\n%s:\\n"'%(sym(name).replace('"','\\"'),sym(name).replace('"','\\"')))
    for a,l in b:
        lab=''
        if a in need: lab='.Llt_%08x:\\n'%a
        out.append('  "%s  %s\\n"'%(lab,l.replace('"','\\"')))
    out.append(');')
out.append('__asm__(".att_syntax prefix\\n");')
# jump-table targets: data dwords pointing at an instruction inside a lifted function
img=open('ltdata.bin','rb').read(); lo=base+0xcb000
extra={}
entries={va for _,va,_,_ in lifted}
for k in range(0,len(img)-3,4):
    v=int.from_bytes(img[k:k+4],'little')
    if v in allinstr and v not in entries: extra[v]=1
# need global labels for them: add after-the-fact by re-emitting with extra labels
if extra:
    out=[];  # regenerate with global labels
    need|=set(extra)
    out.append('/* generated by lift_stubs.py */'); out.append('__asm__(".intel_syntax noprefix\\n");')
    for name,va,b in bodies:
        out.append('__asm__(".text\\n.p2align 4\\n.globl %s\\n%s:\\n"'%(sym(name).replace('"','\\"'),sym(name).replace('"','\\"')))
        for a,l in b:
            lab=''
            if a in need: lab='.Llt_%08x:\\n'%a
            if a in extra: lab+='.globl _lt_L_%08x\\n_lt_L_%08x:\\n'%(a,a)
            out.append('  "%s  %s\\n"'%(lab,l.replace('"','\\"')))
        out.append(');')
    out.append('__asm__(".att_syntax prefix\\n");')
json.dump([b[0] for b in bodies],open('lifted_names.json','w'))
open('c/lt_lifted.c','w').write('\n'.join(out)+'\n')
json.dump({hex(k):'lt_L_%08x'%k for k in extra},open('lifted_labels.json','w'))
json.dump([[w[0],*map(str,w[1:])] for w in warn],open('lift_warnings.json','w'),indent=0)
print('lifted',len(bodies),'of',len(stubs),'| jump-table labels',len(extra),'| warnings',len(warn))
print(collections.Counter(w[0] for w in warn))
